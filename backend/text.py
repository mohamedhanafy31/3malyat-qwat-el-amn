"""تطبيع النص العربي — الوحدة الوحيدة المسؤولة عن ده في السيستم كله.

مفيش أي اعتماد على flask ولا على باقي الحزمة، عشان سكربتات الاستيراد
(اللي بتشتغل لوحدها من مجلد import_archive) تقدر تستوردها هي كمان —
فيفضل التطبيع واحد في الاستيراد وفي التطبيق. اختلاف حرف واحد بين
الاتنين معناه خدمة ما تتطابقش وتقع في «الصافي» من غير ما حد ياخد باله.
"""
import re

_DIACRITICS = re.compile(r'[ؐ-ًؚ-ٰٟۖ-ۭـ]')

# صور الحرف الواحدة اللي بتتكتب بأكتر من شكل في المصدر
_FOLD = (
    ('أ', 'ا'), ('إ', 'ا'), ('آ', 'ا'), ('ٱ', 'ا'),
    ('ى', 'ي'), ('ة', 'ه'), ('ؤ', 'و'), ('ئ', 'ي'),
)


def norm(s):
    """صورة موحّدة للمقارنة: بلا تشكيل، همزات وتاء مربوطة وألف مقصورة
    موحّدة، وعلامات الترقيم بمسافة. مش للعرض — للمطابقة بس.

    مثال على اللي بتحله فعليًا في الأرشيف:
      «عمل بهدف السخئة» == «عمل بهدف السخنه»؟  لأ — دي غلطة إملائية
      حقيقية بتتعالج بالـaliases مش بالتطبيع.
      «نقطة التفتيش» == «نقطه تفتيش»؟ أيوه — دي بتتحل هنا.
    """
    s = _DIACRITICS.sub('', s or '')
    for a, b in _FOLD:
        s = s.replace(a, b)
    s = re.sub(r'[^؀-ۿ\w]+', ' ', s)
    return re.sub(r'\s+', ' ', s).strip()


def norm_name(s):
    """زي norm بس بتلزّق البادئات اللي بتتكتب موصولة ومفصولة (عبد / ابو / ابن)."""
    return re.sub(r'\b(عبد|ابو|ابن)\s+', r'\1', norm(s)).strip()


# الكلمات اللي بتوصف الفترة أو الوقت أو الجهة جوّه اسم الخدمة في الورد
# («تدخل سريع صبح»، «ترحيلة بدر 7ص "عتاقة"»). بتتشال قبل المطابقة عشان
# الاسم يوصل لصورته المجرّدة اللي في الكتالوج.
_SHIFT_WORDS = r'(?:فتره\s+)?(?:صباحيه|ليليه|صبح|ليل)'
_TIME = r'\d{1,2}(?::\d{2})?\s*(?:ص|م|ظ)\b'


def core_service_name(s):
    """اسم الخدمة مجرّدًا من الفترة والساعة والجهة بين علامتي تنصيص."""
    s = re.sub(r'["“”«»\'][^"“”«»\']*["“”«»\']', ' ', s or '')   # الجهة: "عتاقة"
    s = norm(s)
    s = re.sub(_TIME, ' ', s)
    s = re.sub(rf'\b{_SHIFT_WORDS}\b', ' ', s)
    return re.sub(r'\s+', ' ', s).strip()
