#!/usr/bin/env python3
"""تصنيف تشغيل الضابط اليومي حسب جدول الإجمالي أسفل يومية الضباط.

الجدول بيقسّم أصل القوة إلى:
  الخدمات الخارجية (صباحية/ليلية) — خدمات برّه الإدارة
  الخدمات الداخلية (صباحية/ليلية) — خدمات جوّه الإدارة
  الخدمات الطبية (موجود/راحة)     — العيادة + المنتدب من قطاع الخدمات الطبية
  الخوارج (تقصيرة/راحة/طارئة/غياب/مرضي/فرقة/انتداب)
  الحراسات المشددة                — عمل بهدف أو مشرف الأهداف
  الصافي                          — الباقي المتاح (قيادات ومتابعة أعمال)

كل ضابط بيروح لخانة واحدة بس، بالترتيب اللي تحت.

⚠ حالة التحقق (اتقيست على يوميات 20/8 → 31/8، 12 يوم):
  • الخوارج (راحة/تقصيرة/طارئة/غياب/مرضي/فرقة/انتداب) والحراسات والطبية
    → مطابقة 10–12 يوم من 12. موثوقة.
  • التقسيم بين "خارجية" و"داخلية" و"صافي"
    → مش مضبوط (يوم واحد من 12). محتاج كتالوج خدمات كل خدمة متعلّم عليها
      داخلية/خارجية، لأن التصنيف ده معرفة تشغيلية مش موجودة في نص التشغيل.

الملف ده أداة تحليل لسه مش متوصلة بالتطبيق.
"""
import re
from common import strip_ar

# المجموعات كما تظهر في الجدول
EXTERNAL, INTERNAL, MEDICAL = "خارجية", "داخلية", "طبية"
OUT, GUARD, NET = "خوارج", "حراسات", "صافي"

MORNING, NIGHT, BOTH = "صباحية", "ليلية", "صباحية+ليلية"

# مناصب القيادة — دايمًا ضمن الصافي مهما كان التشغيل
LEADER_POSTS = ("مدير الاداره", "وكيل الاداره", "قائد المعسكر الفرعي")
MEDICAL_POSTS = ("العياده الطبيه", "قطاع الخدمات الطبيه", "الخدمات الطبيه")

# خدمات داخل الإدارة
INTERNAL_HINTS = ("ضابط عظيم", "امن الاداره", "ضابط امن", "نوبتجي")


def shift(duty):
    """الفترة المذكورة في نص التشغيل."""
    n = strip_ar(duty)
    m, l = "صباحيه" in n or re.search(r'\d\s*ص\b', n), "ليليه" in n or re.search(r'\d\s*م\b', n)
    if m and l:
        return BOTH
    if l:
        return NIGHT
    return MORNING          # الافتراضي صباحية


def classify(row):
    """-> (group, bucket) لكل ضابط في اليومية."""
    duty, post = strip_ar(row.get("duty", "")), strip_ar(row.get("post", ""))

    # 1) الخدمات الطبية: العيادة والمنتدب من القطاع الطبي
    if any(k in post for k in MEDICAL_POSTS):
        return (MEDICAL, "راحة" if ("راح" in duty or "جاز" in duty) else "موجود")

    # 2) الخوارج — الغياب والراحات لها الأولوية على أي تشغيل
    if "غياب" in duty:
        return (OUT, "غياب")
    if "مرضي" in duty:
        return (OUT, "مرضي")
    if "طاري" in duty:
        return (OUT, "طارئة")
    if "راح" in duty or "جاز" in duty:
        return (OUT, "راحة")
    if "انتداب" in duty:
        return (OUT, "انتداب")
    if "فرقه" in duty:
        return (OUT, "فرقة")
    # التقصيرة بتغلب الخدمة: الضابط اشتغل وخرج بدري
    if "تقصير" in duty:
        return (OUT, "تقصيرة")

    # 3) الحراسات المشددة: تأمين هدف أو الإشراف على الأهداف
    if "عمل بهدف" in duty or "مشرف الاهداف" in duty:
        return (GUARD, "")

    # 4) القيادات بدون خدمة محددة
    if any(k in post for k in LEADER_POSTS):
        return (NET, "")

    # 5) خدمة داخلية أو خارجية
    if any(k in duty for k in INTERNAL_HINTS):
        return (INTERNAL, shift(duty))
    if "فتره" in duty or re.search(r'\d\s*[صم]\b', duty):
        return (EXTERNAL, shift(duty))

    # 6) متابعة أعمال بدون خدمة => صافي
    return (NET, "")
